"""Build app/static/worldmap.svg (offline, run once; output is committed).

Source: Natural Earth land polygons (public domain, https://www.naturalearthdata.com/):
  world  = ne_110m_land.geojson, Europe zoom = ne_50m_land.geojson clipped to the zoom box.
Projection: Miller cylindrical, x = lon, y = 1.25 * ln(tan(pi/4 + 0.4 * lat)) (degrees).
The SVG root carries each view's box as data-* attributes so app/static/dcmap.js projects
datacenter coordinates with exactly the same numbers.

  python tools/gen_worldmap.py ne_110m_land.geojson ne_50m_land.geojson
Needs shapely (dev only, not a runtime dependency)."""
import json
import math
import os
import sys

from shapely.geometry import box, shape
import warnings

from shapely.ops import transform, unary_union

warnings.filterwarnings("ignore", category=DeprecationWarning)

VIEWS = {  # id: (lon0, lon1, lat0, lat1, width in SVG units, simplify tolerance)
    "world": (-168.0, 180.0, -56.0, 78.0, 1000.0, 0.9),
    "europe": (-5.0, 23.0, 41.0, 57.5, 600.0, 0.6),
}


def miller(lat: float) -> float:
    lat = max(-85.0, min(85.0, lat))
    return math.degrees(1.25 * math.log(math.tan(math.pi / 4 + 0.4 * math.radians(lat))))


def build(src: str, vid: str) -> tuple[str, dict]:
    lon0, lon1, lat0, lat1, W, tol = VIEWS[vid]
    y0, y1 = miller(lat1), miller(lat0)        # top, bottom (y grows downwards in SVG)
    k = W / (lon1 - lon0)
    H = round((y0 - y1) * k, 1)
    geo = unary_union([shape(f["geometry"]) for f in json.load(open(src))["features"]])
    geo = geo.intersection(box(lon0 - 1, lat0 - 1, lon1 + 1, lat1 + 1))
    proj = transform(lambda x, y, z=None: ((x - lon0) * k, (y0 - miller(y)) * k), geo)
    proj = proj.simplify(tol, preserve_topology=True)
    polys = getattr(proj, "geoms", [proj])
    parts = []
    for p in polys:
        if p.is_empty or p.area < tol * tol * 2:
            continue
        for ring in [p.exterior, *p.interiors]:
            pts = list(ring.coords)[:-1]
            if len(pts) < 3:
                continue
            parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    meta = {"lon0": lon0, "lon1": lon1, "lat0": lat0, "lat1": lat1, "w": W, "h": H}
    return "".join(parts), meta


def main():
    s110, s50 = sys.argv[1], sys.argv[2]
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "static", "worldmap.svg")
    paths, attrs = [], []
    for vid, src in (("world", s110), ("europe", s50)):
        d, m = build(src, vid)
        paths.append(f'<path id="{vid}" d="{d}"/>')
        attrs.append(f'data-{vid}="{m["lon0"]},{m["lon1"]},{m["lat0"]},{m["lat1"]},{m["w"]},{m["h"]}"')
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" ' + " ".join(attrs) + '>\n'
           '<!-- Land: Natural Earth (public domain), Miller projection. Generated by tools/gen_worldmap.py -->\n'
           + "\n".join(paths) + "\n</svg>\n")
    open(out, "w").write(svg)
    print(out, len(svg), "bytes")


if __name__ == "__main__":
    main()
